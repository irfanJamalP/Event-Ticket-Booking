BEGIN;

CREATE TABLE IF NOT EXISTS admin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(200) NOT NULL UNIQUE,
    password TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS customer (
    kode_customer VARCHAR(100) PRIMARY KEY,
    nama VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    telp VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS produk (
    kode_produk VARCHAR(100) PRIMARY KEY,
    nama VARCHAR(100) NOT NULL,
    image TEXT NOT NULL,
    deskripsi TEXT NOT NULL,
    harga BIGINT NOT NULL CHECK (harga >= 0)
);

CREATE TABLE IF NOT EXISTS inventory (
    kode_bk VARCHAR(100) PRIMARY KEY,
    nama VARCHAR(200) NOT NULL,
    qty NUMERIC(12, 3) NOT NULL DEFAULT 0 CHECK (qty >= 0),
    satuan VARCHAR(200) NOT NULL,
    harga BIGINT NOT NULL DEFAULT 0 CHECK (harga >= 0),
    tanggal DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS bom_produk (
    kode_bom VARCHAR(100) PRIMARY KEY,
    kode_bk VARCHAR(100) NOT NULL,
    kode_produk VARCHAR(100) NOT NULL,
    nama_produk VARCHAR(200) NOT NULL,
    kebutuhan NUMERIC(12, 3) NOT NULL CHECK (kebutuhan >= 0)
);

CREATE TABLE IF NOT EXISTS keranjang (
    id_keranjang BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_customer VARCHAR(100) NOT NULL,
    kode_produk VARCHAR(100) NOT NULL,
    nama_produk VARCHAR(100) NOT NULL,
    qty INTEGER NOT NULL CHECK (qty > 0),
    harga BIGINT NOT NULL CHECK (harga >= 0),
    UNIQUE (kode_customer, kode_produk)
);

CREATE TABLE IF NOT EXISTS metode_pembayaran (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(50) NOT NULL,
    data VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS produksi (
    id_order BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice VARCHAR(200) NOT NULL,
    kode_customer VARCHAR(200) NOT NULL,
    kode_produk VARCHAR(200) NOT NULL,
    nama_produk VARCHAR(200) NOT NULL,
    qty INTEGER NOT NULL CHECK (qty > 0),
    harga BIGINT NOT NULL CHECK (harga >= 0),
    status VARCHAR(200) NOT NULL,
    tanggal DATE NOT NULL,
    provinsi VARCHAR(200) NOT NULL,
    kota VARCHAR(200) NOT NULL,
    alamat VARCHAR(200) NOT NULL,
    kode_pos VARCHAR(20) NOT NULL,
    terima VARCHAR(200) NOT NULL DEFAULT '0',
    tolak VARCHAR(200) NOT NULL DEFAULT '0',
    cek INTEGER NOT NULL DEFAULT 0,
    metode_pembayaran_id BIGINT,
    bukti_pembayaran VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS report_penjualan (
    id_report_sell BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice VARCHAR(100) NOT NULL,
    kode_produk VARCHAR(100) NOT NULL,
    nama_produk VARCHAR(100) NOT NULL,
    jumlah_terjual INTEGER NOT NULL,
    tanggal DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS report_cancel (
    id_report_cancel BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_order VARCHAR(100) NOT NULL,
    kode_produk VARCHAR(100) NOT NULL,
    jumlah INTEGER NOT NULL,
    tanggal DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS report_inventory (
    id_report_inv BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_bk VARCHAR(100) NOT NULL,
    nama_bahanbaku VARCHAR(100) NOT NULL,
    jml_stok_bk NUMERIC(12, 3) NOT NULL,
    tanggal DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS report_omset (
    id_report_omset BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice VARCHAR(100) NOT NULL,
    jumlah INTEGER NOT NULL,
    total_omset BIGINT NOT NULL,
    tanggal DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS report_produksi (
    id_report_prd BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice VARCHAR(100) NOT NULL,
    kode_produk VARCHAR(100) NOT NULL,
    nama_produk VARCHAR(100) NOT NULL,
    qty INTEGER NOT NULL,
    tanggal DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS report_profit (
    id_report_profit BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_bom VARCHAR(100) NOT NULL UNIQUE,
    invoice VARCHAR(100) NOT NULL,
    kode_produk VARCHAR(100) NOT NULL,
    jumlah NUMERIC(12, 3) NOT NULL,
    total_profit BIGINT NOT NULL,
    tanggal DATE NOT NULL
);

CREATE INDEX IF NOT EXISTS keranjang_customer_idx ON keranjang (kode_customer);
CREATE INDEX IF NOT EXISTS produksi_invoice_idx ON produksi (invoice);
CREATE INDEX IF NOT EXISTS produksi_customer_idx ON produksi (kode_customer);
CREATE INDEX IF NOT EXISTS produksi_status_idx ON produksi (status);
CREATE INDEX IF NOT EXISTS bom_produk_product_idx ON bom_produk (kode_produk);
CREATE INDEX IF NOT EXISTS bom_produk_inventory_idx ON bom_produk (kode_bk);

